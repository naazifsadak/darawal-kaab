-- 8. Create notifications table
drop table if exists public.notifications cascade;
create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null, -- The user receiving the notification
  sender_id uuid references public.profiles(id) on delete cascade not null, -- The user who triggered the notification
  type text not null check (type in ('like', 'comment', 'follow')),
  post_id uuid references public.posts(id) on delete cascade, -- Nullable for follow notifications
  is_read boolean default false not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.notifications enable row level security;

drop policy if exists "Users can view own notifications" on notifications;
drop policy if exists "System can insert notifications" on notifications;
drop policy if exists "Users can update own notifications" on notifications;

create policy "Users can view own notifications" on notifications for select using ( auth.uid() = user_id );
create policy "System can insert notifications" on notifications for insert with check (true);
create policy "Users can update own notifications" on notifications for update using ( auth.uid() = user_id );

-- 9. Triggers to create notifications
create or replace function public.create_notification_on_like()
returns trigger as $$
declare
  post_author uuid;
begin
  -- Get the author of the post
  select author_id into post_author from public.posts where id = new.post_id;
  
  -- Don't notify if liking own post
  if post_author != new.user_id then
    insert into public.notifications (user_id, sender_id, type, post_id)
    values (post_author, new.user_id, 'like', new.post_id);
  end if;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_like_notification on public.post_likes;
create trigger on_like_notification
  after insert on public.post_likes
  for each row execute function public.create_notification_on_like();

create or replace function public.create_notification_on_comment()
returns trigger as $$
declare
  post_author uuid;
begin
  select author_id into post_author from public.posts where id = new.post_id;
  
  if post_author != new.author_id then
    insert into public.notifications (user_id, sender_id, type, post_id)
    values (post_author, new.author_id, 'comment', new.post_id);
  end if;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_comment_notification on public.comments;
create trigger on_comment_notification
  after insert on public.comments
  for each row execute function public.create_notification_on_comment();

create or replace function public.create_notification_on_follow()
returns trigger as $$
begin
  insert into public.notifications (user_id, sender_id, type)
  values (new.following_id, new.follower_id, 'follow');
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_follow_notification on public.follows;
create trigger on_follow_notification
  after insert on public.follows
  for each row execute function public.create_notification_on_follow();
