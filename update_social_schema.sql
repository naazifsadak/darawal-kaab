-- 1. Create post_likes table
drop table if exists public.post_likes cascade;
create table public.post_likes (
  id bigint generated by default as identity primary key,
  post_id uuid references public.posts(id) on delete cascade not null,
  user_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(post_id, user_id)
);

alter table public.post_likes enable row level security;

drop policy if exists "Anyone can view likes" on post_likes;
drop policy if exists "Authenticated users can like posts" on post_likes;
drop policy if exists "Users can unlike posts" on post_likes;

create policy "Anyone can view likes" on post_likes for select using ( true );
create policy "Authenticated users can like posts" on post_likes for insert with check ( auth.uid() = user_id );
create policy "Users can unlike posts" on post_likes for delete using ( auth.uid() = user_id );

-- 2. Create follows table
drop table if exists public.follows cascade;
create table public.follows (
  id bigint generated by default as identity primary key,
  follower_id uuid references public.profiles(id) on delete cascade not null,
  following_id uuid references public.profiles(id) on delete cascade not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  unique(follower_id, following_id)
);

alter table public.follows enable row level security;

drop policy if exists "Anyone can view follows" on follows;
drop policy if exists "Authenticated users can follow" on follows;
drop policy if exists "Users can unfollow" on follows;

create policy "Anyone can view follows" on follows for select using ( true );
create policy "Authenticated users can follow" on follows for insert with check ( auth.uid() = follower_id );
create policy "Users can unfollow" on follows for delete using ( auth.uid() = follower_id );

-- 3. Add comments_count to posts
alter table public.posts add column if not exists comments_count integer default 0;

-- 4. Triggers to maintain likes_count on posts
create or replace function public.handle_like()
returns trigger as $$
begin
  if (tg_op = 'INSERT') then
    update public.posts set likes_count = likes_count + 1 where id = new.post_id;
    return new;
  elsif (tg_op = 'DELETE') then
    update public.posts set likes_count = likes_count - 1 where id = old.post_id;
    return old;
  end if;
  return null;
end;
$$ language plpgsql security definer;

drop trigger if exists on_like_created on public.post_likes;
create trigger on_like_created
  after insert or delete on public.post_likes
  for each row execute function public.handle_like();

