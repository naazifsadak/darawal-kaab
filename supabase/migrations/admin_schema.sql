-- 1. ADD COLUMNS TO PROFILES IF THEY DON'T EXIST
alter table public.profiles add column if not exists is_admin boolean default false;
alter table public.profiles add column if not exists status text default 'active' check (status in ('active', 'suspended'));

-- 2. CREATE BANNERS TABLE FOR SYSTEM ANNOUNCEMENTS
create table if not exists public.app_banners (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  severity text not null default 'info' check (severity in ('info', 'warning', 'critical')),
  is_active boolean default true not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  created_by uuid references public.profiles(id) on delete set null
);

-- ENABLE ROW LEVEL SECURITY
alter table public.app_banners enable row level security;

-- 3. POLICIES (Drop first to avoid conflicts)
drop policy if exists "Anyone can view active banners" on public.app_banners;
drop policy if exists "Admins can manage banners" on public.app_banners;

create policy "Anyone can view active banners" on public.app_banners 
  for select using (is_active = true);

create policy "Admins can manage banners" on public.app_banners 
  for all using (
    exists (
      select 1 from public.profiles 
      where id = auth.uid() and is_admin = true
    )
  );

-- 4. UPDATE EXISTING POLICIES TO ALLOW ADMIN TO DELETE/UPDATE CONTENT
-- Ensure admins can delete any posts
drop policy if exists "Admins can delete any post" on public.posts;
create policy "Admins can delete any post" on public.posts
  for delete using (
    exists (
      select 1 from public.profiles
      where id = auth.uid() and is_admin = true
    )
  );

-- Ensure admins can delete any comment
drop policy if exists "Admins can delete any comment" on public.comments;
create policy "Admins can delete any comment" on public.comments
  for delete using (
