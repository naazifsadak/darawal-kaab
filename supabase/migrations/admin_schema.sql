    exists (
      select 1 from public.profiles
      where id = auth.uid() and is_admin = true
    )
  );

-- 5. SECURE ADMIN AND BAN STATUS WITH A DATABASE TRIGGER
-- Prevents standard users from promoting themselves to admin or unsuspending themselves.
create or replace function public.check_user_privileges_on_update()
returns trigger as $$
begin
  -- Check if the trigger is running for the user updating their own profile
  if auth.uid() = new.id then
    -- Non-admin cannot promote themselves to admin
    if old.is_admin = false and new.is_admin = true then
      -- Verify if the current session belongs to an existing admin doing the change
      if not exists (select 1 from public.profiles where id = auth.uid() and is_admin = true) then
        raise exception 'Access Denied: You cannot make yourself an admin.';
      end if;
    end if;

    -- Standard user cannot unsuspend themselves if they are suspended
    if old.status = 'suspended' and new.status = 'active' then
      if not exists (select 1 from public.profiles where id = auth.uid() and is_admin = true) then
        raise exception 'Access Denied: You cannot unsuspend your own account.';
      end if;
    end if;
  end if;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists enforce_profile_security on public.profiles;
create trigger enforce_profile_security
  before update on public.profiles
  for each row execute function public.check_user_privileges_on_update();

